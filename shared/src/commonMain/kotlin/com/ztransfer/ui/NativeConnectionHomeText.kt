    fun label(language: String, chinese: String, english: String): String {
        val code = language.lowercase()
        return when {
            !code.startsWith("zh") -> english
            code.contains("hant") || code.endsWith("-tw") || code.endsWith("-hk") || code.endsWith("-mo") ->
                traditional[chinese] ?: chinese
            else -> chinese
        }
    }
    internal fun hasTraditional(chinese: String): Boolean = chinese in traditional
